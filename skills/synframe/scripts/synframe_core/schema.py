class ContractError(ValueError):
    """Rejected state change with a reason usable by the host controller."""
    def __init__(self, message, *, details=None):
        super().__init__(message)
        self.details = details or {}


def require(ok, message):
    if not ok:
        raise ContractError(message)


def typed(value, kind):
    return type(value) is kind


def ref(value):
    require(isinstance(value, dict) and set(value) == {"id", "revision"},
            "reference must contain exactly id and revision")
    require(type(value["id"]) is str and bool(value["id"]), "empty reference id")
    require(type(value["revision"]) is int and value["revision"] > 0, "invalid reference revision")
    return value


def references(value):
    """Only explicit {id,revision} objects are references; names are not IDs."""
    if isinstance(value, dict):
        if set(value) == {"id", "revision"}:
            yield ref(value)
        else:
            for child in value.values():
                yield from references(child)
    elif isinstance(value, list):
        for child in value:
            yield from references(child)


def finite_json(value):
    if isinstance(value, float):
        require(math.isfinite(value), "non-finite measurement")
    elif isinstance(value, dict):
        for child in value.values():
            finite_json(child)
    elif isinstance(value, list):
        for child in value:
            finite_json(child)


def ports(items):
    names = set()
    for port in items:
        require(isinstance(port, dict) and set(port) == {"name", "type"}, "port requires name/type")
        require(all(type(v) is str and v.strip() for v in port.values()), "empty port")
        require(port["name"] not in names, "duplicate port")
        names.add(port["name"])


def validate(doc, *, patch=False):
    finite_json(doc)
    require(isinstance(doc, dict), "entity must be an object")
    kind = doc.get("type")
    require(kind in FIELDS, "unknown entity type")
    require(({"id", "type"} if patch else META) <= set(doc), "missing common metadata")
    if patch:
        require(not (set(doc) & (META - {"id", "type", "provenance", "validity_status"})),
                "metadata is core-owned")
    require(set(doc) <= META | set(FIELDS[kind]) | set(OPTIONAL), "unknown entity field; use extensions")
    if not patch:
        require(doc["schema_version"] == SCHEMA_VERSION, "unsupported entity schema")
        require(type(doc["revision"]) is int and doc["revision"] > 0, "invalid entity revision")
    require(doc.get("validity_status", "VALID") in VALIDITY, "invalid validity status")
    for name in (["id"] if patch else ["id", "created_at", "updated_at", "source_run_id"]):
        require(type(doc[name]) is str and bool(doc[name]), f"invalid metadata {name}")
    require(type(doc.get("provenance", [])) is list, "provenance must be a list")
    for name, expected in (FIELDS[kind] | {k: v for k, v in OPTIONAL.items() if k in doc}).items():
        require(name in doc and typed(doc[name], expected), f"{kind}.{name} requires {expected.__name__}")
        if expected is str:
            require(bool(doc[name].strip()), f"empty {kind}.{name}")
    for value in references(doc):
        ref(value)
    for key in {"gaps", "unresolved_items", "uncertainties"} & set(doc):
        for item in doc[key]:
            if isinstance(item, dict) and "important" in item:
                require(type(item["important"]) is bool and type(item.get("description")) is str and item["description"], "uncertainty importance requires a boolean and description")
    # Typed direct references and lists reject malformed near-reference objects.
    for key, value in doc.items():
        if key.endswith("_ref"):
            ref(value)
        elif (key.endswith("_refs") and key not in {"artifact_refs", "file_refs"}
              and not (kind == "LearningTask" and key == "dependency_refs")) or (kind == "DependencyLink" and key == "sources"):
            require(type(value) is list, f"{key} must be a list")
            for item in value:
                ref(item)
    if "inputs" in doc:
        ports(doc["inputs"]); ports(doc["outputs"])
    if kind == "LearningTask":
        from .learning import validate_shape
        validate_shape(doc)
    elif kind == "GoalSpec":
        require(doc["outcome_type"] in RECORD_ENUMS['GoalSpec.outcome_type'], "invalid outcome type")
        require(bool(doc["success_criteria"]), "goal needs observable success criteria")
        ids = set()
        for criterion in doc["success_criteria"]:
            require(type(criterion) is dict and set(criterion) == {"id", "description"}, "criterion requires id/description")
            require(all(type(v) is str and v for v in criterion.values()), "empty criterion")
            require(criterion["id"] not in ids, "duplicate criterion")
            ids.add(criterion["id"])
        ids = set()
        for constraint in doc["explicit_constraints"]:
            require(type(constraint) is dict and set(constraint) == {"id", "description", "predicate"}, "constraint requires id/description/predicate")
            require(type(constraint["id"]) is str and constraint["id"] not in ids, "duplicate constraint")
            ids.add(constraint["id"])
            p = constraint["predicate"]
            if p is not None:
                require(type(p) is dict and set(p) == {"path", "op", "value"}, "invalid predicate")
                require(type(p["path"]) is str and p["op"] in {"eq", "in", "not_in", "gte", "lte", "exists"}, "unsupported predicate")
    elif kind == "Frame":
        require(doc["transformation"] in FRAME_AXES, "invalid Frame axis")
        require(doc["structural_difference"].get("rationale"), "Frame requires meaningful difference rationale")
        require(doc["information_requirements"], "Frame requires information needs: information_requirements must contain actual canonical LearningTask refs. Connect existing relevant questions or explicitly register needed questions; later scope registration does not fill this field.")
    elif kind == "Capability":
        require(doc["origin"] in RECORD_ENUMS['Capability.origin'], "capability origin must remain explicit/inferred")
    elif kind == "EvidenceRecord":
        require(doc["observation_kind"] in RECORD_ENUMS['EvidenceRecord.observation_kind'], "invalid observation kind")
        require(doc["verification_status"] in RECORD_ENUMS['EvidenceRecord.verification_status'], "invalid evidence status")
        require(not (doc["observation_kind"] == "unknown" and doc["verification_status"] == "VERIFIED"), "unknown cannot be verified")
    elif kind == "KnowledgeAsset":
        require(doc["availability"] in RECORD_ENUMS['KnowledgeAsset.availability'], "invalid availability")
        for k in doc["understanding"]:
            require(type(k) is dict and {"context", "level", "questions", "evidence_refs", "stop_condition"} == set(k), "invalid contextual K assessment")
            require(type(k["level"]) is int and 0 <= k["level"] <= 4, "K level outside K0-K4")
            require(type(k["context"]) is str and k["context"], "K requires context/version")
            require(type(k["questions"]) is list and type(k["stop_condition"]) is str and k["stop_condition"], "K needs questions/stop condition")
            for r in k["evidence_refs"]:
                ref(r)
    elif kind == "DependencyLink":
        require(doc["sources"] and doc["evidence_refs"], "dependency requires sources and evidence")
        from .learning import ROLES
        require(doc["relation"] in {"AND", "OR", "REQUIRES", "PROVIDES", "TRANSFORMS", "CONFLICTS", "ENABLES"} | ROLES, "unknown graph relation")
    elif kind == "SolutionCandidate":
        require(doc["disposition"] in RECORD_ENUMS['SolutionCandidate.disposition'], "invalid candidate disposition")
        for c in doc["connections"]:
            require(type(c) is dict and set(c) == {"from_ref", "output", "to_ref", "input", "evidence_refs"}, "invalid I/O connection")
            ref(c["from_ref"]); ref(c["to_ref"])
            require(c["evidence_refs"], "connection needs evidence")
            for r in c["evidence_refs"]:
                ref(r)
    elif kind == "DecisionRecord":
        validate_decision(doc)
    elif kind == "ReviewRecord":
        for r in doc["snapshot"]:
            ref(r)
        require(REVIEW_CHECKS <= set(doc["checks"]), "missing semantic Review checks")
        for check in doc["checks"].values():
            require(type(check) is dict and set(check) == {"status", "rationale", "evidence_refs"}, "invalid Review check")
            require(check["status"] in {"PASS", "FAIL", "UNKNOWN"}, "invalid Review status")
            require(type(check["rationale"]) is str and check["rationale"], "Review requires rationale")
            require(type(check["evidence_refs"]) is list, "Review evidence must be list")
            for r in check["evidence_refs"]:
                ref(r)
    elif kind == "SolutionPackage":
        require(set(doc["contents"]) == PACKAGE_FIELDS, "SolutionPackage needs all ten output fields")
        for artifact in doc["artifact_refs"]:
            require(type(artifact) is dict and set(artifact) == {"path", "sha256", "source"}, "artifact needs path/hash/source")
            require(all(type(v) is str and v for v in artifact.values()), "invalid artifact metadata")
            require(len(artifact["sha256"]) == 64 and all(c in "0123456789abcdef" for c in artifact["sha256"]), "invalid artifact hash")
    return doc


def candidate_patch(doc):
    """Discard copied core projections, not host-authored proof/selection grounds.

    apply recalculates these values from the actual current graph. Other
    extensions, literal references and historical records remain untouched.
    """
    if doc.get("type") != "SolutionCandidate":
        return doc
    return {**doc, "extensions": {k: v for k, v in doc.get("extensions", {}).items()
        if k not in {"functional_proof_refs", "selection_validity"}}}


def validate_result_shape(result):
    """Shared authoring/apply shape checks; no state lookup or semantic approval."""
    def no_markers(value, path):
        if type(value) is dict:
            require("$patch_ref" not in value,
                    path + ": unresolved patch_ref; call build_result again after all edits, then reassess closure basis")
            for key, child in value.items():
                no_markers(child, path + "." + key)
        elif type(value) is list:
            for i, child in enumerate(value):
                no_markers(child, f"{path}[{i}]")
    require(type(result) is dict and set(result) == RESULT_FIELDS, "invalid operation output fields")
    no_markers(result, "result")
    require(type(result["operation_id"]) is str and result["operation_id"], "invalid operation output id")
    require(result["outcome"] in {"SUCCEEDED", "FAILED", "UNKNOWN"}, "invalid operation outcome")
    for key in RESULT_FIELDS - {"operation_id", "outcome"}:
        require(type(result[key]) is list, f"result {key} must be list")
    for key in ("result_refs", "evidence_refs"):
        for pointer in result[key]:
            ref(pointer)
    for change in result["proposed_state_changes"]:
        require(type(change) is dict, "change needs id/type")
        try:
            validate(change, patch=True)
        except ContractError as exc:
            raise ContractError(f"{change.get('id', '?')} ({change.get('type', '?')}): {exc}") from exc
    for i, record in enumerate(result["learning_results"]):
        require(type(record) is dict and set(record) == LEARNING_RESULT_FIELDS,
                f"learning_results[{i}] needs four actual result bundles")
        for key in ("task_ref", "result_ref"):
            ref(record[key])
        require(type(record["answer_refs"]) is list, "learning answer_refs must be a list of EvidenceRecord refs")
        for pointer in record["answer_refs"]:
            ref(pointer)
        task = next((change for change in result['proposed_state_changes']
            if change.get('type') == 'LearningTask' and change['id'] == record['result_ref']['id']), None)
        if task is not None:
            validate_discovery_ids(record, task, f'learning_results[{i}].discovery_ids')
    return result


def validate_discovery_ids(record, task, field):
    """Compare declared IDs with the complete resulting task, never fill them."""
    supplied = record['discovery_ids']
    require(type(supplied) is list and all(type(item) is str and item for item in supplied),
            field + ' must be an explicit list of stable discovery ID strings')
    expected = {item['id'] for item in task['expansion']['discoveries']}
    actual = set(supplied)
    if actual != expected:
        details = {'field':field, 'task_ref':record['result_ref'],
            'expected_ids':sorted(expected), 'missing_ids':sorted(expected-actual),
            'unexpected_ids':sorted(actual-expected)}
        raise ContractError(f"{field} for {task['id']}@{record['result_ref']['revision']}: "
            f"result discovery evaluation omitted items or contains unexpected IDs; "
            f"expected={details['expected_ids']}, missing={details['missing_ids']}, "
            f"unexpected={details['unexpected_ids']}. Include all retained and new discoveries "
            "in the resulting expansion, after assessing their current disposition; IDs are not auto-filled.",
            details=details)


def validate_decision(decision):
    require(decision.get("action") in ACTIONS | MANAGEMENT, "unsupported operation action")
    ddc = decision.get("ddc", {})
    require(type(ddc) is dict and set(ddc) == DDC, "DDC requires exactly eight fields")
    require(all(value not in (None, "", [], {}) for key, value in ddc.items() if key != "constraints"), "DDC field has no observable policy content")
    require(type(ddc["constraints"]) is list, "DDC constraints must be a list, possibly empty")
    require(type(ddc["available_actions"]) is list and decision["action"] in ddc["available_actions"], "selected action absent from available actions")
    require(type(decision.get("alternatives")) is list, "decision alternatives must be a list")
    require(type(decision.get("rationale")) is str and decision["rationale"], "decision requires rationale")
    require(type(decision.get("expected_effects")) is list and decision["expected_effects"], "decision needs expected effects")
    for r in decision.get("evidence_refs", []):
        ref(r)


def validate_completion(verification, goal):
    """Shared completion input shape, not success/evidence/goal approval."""
    required = {c['id'] for c in goal['success_criteria']}
    if type(verification) is not dict or set(verification) != required:
        raise ContractError('every success criterion needs actual validation', details={
            'path':'verification', 'expected':{'criterion_ids':sorted(required),
                'each':{k:('list:EvidenceRecord ref' if k=='evidence_refs' else 'host-authored str')
                        for k in sorted(SUCCESS_CHECK_FIELDS)}},
            'actual_keys':sorted(verification) if type(verification) is dict else None})
    for identity, check in verification.items():
        path = 'verification.' + identity
        if type(check) is not dict or set(check) != SUCCESS_CHECK_FIELDS:
            raise ContractError('invalid success validation', details={'path':path,
                'expected_keys':sorted(SUCCESS_CHECK_FIELDS),
                'actual_keys':sorted(check) if type(check) is dict else None})
        require(check['status'] in {'PASS','FAIL','UNKNOWN'}, path + '.status requires PASS/FAIL/UNKNOWN')
        require(type(check['rationale']) is str and check['rationale'].strip(), path + '.rationale requires actual grounds')
        require(type(check['evidence_refs']) is list, path + '.evidence_refs requires EvidenceRecord refs')
        for pointer in check['evidence_refs']:
            ref(pointer)
    return verification


